  const page = pages[decodeURIComponent(location.pathname.split('/').pop())];
  if (!page) return;

  const translations = { ...common, ...page.text };
  const normalize = value => value.trim().replace(/\s+/g, ' ');
  const decorateTextNodes = root => {
    const textNodes = [];
    if (root.nodeType === Node.TEXT_NODE) {
      textNodes.push(root);
    } else {
      const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
      while (walker.nextNode()) textNodes.push(walker.currentNode);
    }

    textNodes.forEach(node => {
      const parent = node.parentElement;
      if (!parent || parent.closest('script, style, .lang-switcher, [data-es][data-en]')) return;

      const english = translations[normalize(node.nodeValue)];
      if (!english) return;

      if (parent.tagName === 'OPTION') {
        parent.dataset.es = node.nodeValue;
        parent.dataset.en = english;
        if (document.documentElement.lang === 'en') parent.textContent = english;
        return;
      }

      const span = document.createElement('span');
      span.dataset.es = node.nodeValue;
      span.dataset.en = english;
      if (document.documentElement.lang === 'en') span.textContent = english;
      node.replaceWith(span);
    });
  };

  decorateTextNodes(document.body);
  new MutationObserver(records => {
    records.forEach(record => record.addedNodes.forEach(decorateTextNodes));
  }).observe(document.body, { childList: true, subtree: true });

  const title = document.querySelector('title');
  title.dataset.es = title.textContent;
  title.dataset.en = page.title;

  const description = document.querySelector('meta[name="description"]');
  if (description && page.description) {
    description.dataset.es = description.content;
    description.dataset.en = page.description;
  }

  const translateAttributes = lang => {
    document.title = lang === 'en' ? page.title : document.querySelector('title')?.dataset.es || document.title;
    document.querySelectorAll('input[placeholder]').forEach(input => {
      const original = input.dataset.placeholderEs || input.placeholder;
      const translated = translations[normalize(original)];
      if (translated) {
        input.dataset.placeholderEs = original;
        input.placeholder = lang === 'en' ? translated : original;
      }
    });
    document.querySelectorAll('img[alt]').forEach(image => {
      const original = image.dataset.altEs || image.alt;
      const translated = translations[normalize(original)];
      if (translated) {
        image.dataset.altEs = original;
        image.alt = lang === 'en' ? translated : original;
      }
    });
    if (description?.dataset.es && description.dataset.en) {
      description.content = lang === 'en' ? description.dataset.en : description.dataset.es;
    }
  };

  const initialLanguage = localStorage.getItem('huskytours-language') === 'en' ? 'en' : 'es';
  translateAttributes(initialLanguage);
  document.querySelectorAll('.lang-btn').forEach(button => {
    button.addEventListener('click', () => translateAttributes(button.dataset.lang));
  });
